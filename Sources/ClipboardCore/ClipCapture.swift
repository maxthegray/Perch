import CryptoKit
import Foundation

public enum ClipKind: String, Sendable, Equatable {
    case text
    case richText
    case image
    case file
}

/// One type's data on one pasteboard item, kept so a clip can be restored exactly as it
/// was copied.
public struct ClipRepresentation: Sendable, Equatable {
    public let itemIndex: Int
    public let type: String
    public let data: Data

    public init(itemIndex: Int, type: String, data: Data) {
        self.itemIndex = itemIndex
        self.type = type
        self.data = data
    }
}

/// What the pasteboard held for one item: every declared type, in the owner's preferred
/// order, and whatever data could be read for them. Marker types such as
/// `org.nspasteboard.ConcealedType` often carry no data, so `types` is what the ignore
/// rules look at.
public struct ClipPasteboardItem: Sendable, Equatable {
    public let types: [String]
    public let data: [String: Data]

    public init(types: [String], data: [String: Data]) {
        self.types = types
        self.data = data
    }
}

public struct ClipCapture: Sendable, Equatable {
    public let kind: ClipKind
    /// Image clips get their pixel size added by the app layer.
    public var title: String
    public let searchText: String
    public let filePaths: [String]
    /// Identifies the clip's content, not its formatting: copying the same text from two
    /// apps, or the same file twice, lands on one clip.
    public let contentHash: String
    public let representations: [ClipRepresentation]
    /// A small PNG for image clips, made by the app layer (this target has no AppKit).
    public var thumbnail: Data?
}

public enum ClipCapturePolicy {
    public static let plainTextType = "public.utf8-plain-text"
    public static let fileURLType = "public.file-url"
    public static let richTextTypes: Set<String> = ["public.rtf", "public.html", "com.apple.flat-rtfd"]
    public static let imageTypes = [
        "public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif"
    ]

    /// Copies that ask not to be remembered (nspasteboard.org) and the private types of
    /// password managers and snippet tools that Maccy also skips.
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ]

    /// Legacy and system-converted flavors of a copy's real types. Restoring the real
    /// types brings them back, and reading them makes the system ask the source app to
    /// convert, which blocks while that app is busy.
    public static func isStoredType(_ type: String) -> Bool {
        !(type.hasPrefix("dyn.")
            || type.hasPrefix("CorePasteboardFlavorType")
            || type.hasSuffix("PboardType")
            || type == "Apple URL pasteboard type"
            || type == "public.utf16-external-plain-text")
    }

    /// Anything larger is left out of history rather than bloating the database.
    public static let maximumBytes = 50 * 1024 * 1024
    static let titleLength = 300
    static let searchTextLength = 20_000

    public static func capture(_ items: [ClipPasteboardItem]) -> ClipCapture? {
        let declared = items.flatMap(\.types)
        guard !declared.contains(where: ignoredTypes.contains) else { return nil }

        var representations: [ClipRepresentation] = []
        for (index, item) in items.enumerated() {
            for type in item.types where isStoredType(type) {
                guard let data = item.data[type], !data.isEmpty else { continue }
                representations.append(ClipRepresentation(itemIndex: index, type: type, data: data))
            }
        }
        guard !representations.isEmpty else { return nil }
        guard representations.reduce(0, { $0 + $1.data.count }) <= maximumBytes else { return nil }

        let fileURLs = representations
            .filter { $0.type == fileURLType }
            .compactMap { String(data: $0.data, encoding: .utf8).flatMap(URL.init(string:)) }
            .filter(\.isFileURL)
        if !fileURLs.isEmpty {
            let paths = fileURLs.map(\.path)
            let names = fileURLs.map(\.lastPathComponent)
            return ClipCapture(
                kind: .file,
                title: String(names.joined(separator: ", ").prefix(titleLength)),
                searchText: (names + paths).joined(separator: "\n"),
                filePaths: paths,
                contentHash: hash("file", paths.joined(separator: "\n").utf8),
                representations: representations
            )
        }

        if let text = representations.first(where: { $0.type == plainTextType })
            .flatMap({ String(data: $0.data, encoding: .utf8) }),
            !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        {
            let isRich = representations.contains { richTextTypes.contains($0.type) }
            return ClipCapture(
                kind: isRich ? .richText : .text,
                title: title(for: text),
                searchText: String(text.prefix(searchTextLength)),
                filePaths: [],
                contentHash: hash("text", text.utf8),
                representations: representations
            )
        }

        if let image = imageTypes.lazy.compactMap({ type in
            representations.first { $0.type == type }
        }).first {
            return ClipCapture(
                kind: .image,
                title: "Image",
                searchText: "",
                filePaths: [],
                contentHash: hash("image", image.data),
                representations: representations
            )
        }

        return nil
    }

    /// The text as one line: whitespace runs (newlines included) collapse to single spaces.
    static func title(for text: String) -> String {
        let words = text.prefix(titleLength * 4).split(whereSeparator: \.isWhitespace)
        return String(words.joined(separator: " ").prefix(titleLength))
    }

    private static func hash<Bytes: Sequence>(_ kind: String, _ bytes: Bytes) -> String
    where Bytes.Element == UInt8 {
        var hasher = SHA256()
        hasher.update(data: Data(kind.utf8))
        hasher.update(data: Data([0]))
        hasher.update(data: Data(bytes))
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}
