import ClipboardCore
import XCTest

final class ClipCapturePolicyTests: XCTestCase {
    func testPlainTextBecomesATextClipWithOneLineTitle() throws {
        let capture = try XCTUnwrap(ClipCapturePolicy.capture([text("  hello\n\n  world  ")]))

        XCTAssertEqual(capture.kind, .text)
        XCTAssertEqual(capture.title, "hello world")
        XCTAssertEqual(capture.searchText, "  hello\n\n  world  ")
        XCTAssertEqual(capture.representations.count, 1)
    }

    func testTextWithRTFIsRichText() throws {
        let item = ClipPasteboardItem(
            types: ["public.rtf", "public.utf8-plain-text"],
            data: ["public.rtf": Data("{\\rtf1 hi}".utf8), "public.utf8-plain-text": Data("hi".utf8)]
        )
        let capture = try XCTUnwrap(ClipCapturePolicy.capture([item]))

        XCTAssertEqual(capture.kind, .richText)
        XCTAssertEqual(capture.representations.map(\.type), ["public.rtf", "public.utf8-plain-text"])
    }

    func testConcealedAndTransientCopiesAreNeverRecorded() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        {
            let item = ClipPasteboardItem(
                types: ["public.utf8-plain-text", marker],
                data: ["public.utf8-plain-text": Data("hunter2".utf8)]
            )
            XCTAssertNil(ClipCapturePolicy.capture([item]), marker)
        }
    }

    func testMarkerOnAnyItemRejectsTheWholeCopy() {
        let marked = ClipPasteboardItem(types: ["org.nspasteboard.ConcealedType"], data: [:])
        XCTAssertNil(ClipCapturePolicy.capture([text("secret"), marked]))
    }

    func testConvertedLegacyFlavorsAreNotStored() throws {
        let types = [
            "public.file-url", "CorePasteboardFlavorType 0x6675726C", "dyn.ah62d4rv4gu8y6y4grf0gn5xbrzw1gydcr7u1e3cytf2gn",
            "NSFilenamesPboardType", "Apple URL pasteboard type", "public.utf16-external-plain-text"
        ]
        let item = ClipPasteboardItem(
            types: types,
            data: Dictionary(uniqueKeysWithValues: types.map { ($0, Data(URL(fileURLWithPath: "/a").absoluteString.utf8)) })
        )
        let capture = try XCTUnwrap(ClipCapturePolicy.capture([item]))

        XCTAssertEqual(capture.representations.map(\.type), ["public.file-url"])
    }

    func testWhitespaceOnlyTextIsSkipped() {
        XCTAssertNil(ClipCapturePolicy.capture([text(" \n\t ")]))
    }

    func testEmptyPasteboardIsSkipped() {
        XCTAssertNil(ClipCapturePolicy.capture([]))
        XCTAssertNil(ClipCapturePolicy.capture([ClipPasteboardItem(types: ["public.utf8-plain-text"], data: [:])]))
    }

    func testCopiedFilesBecomeAFileClipNamedByTheirFiles() throws {
        let capture = try XCTUnwrap(ClipCapturePolicy.capture([
            file("/Users/me/Desktop/report.pdf"), file("/Users/me/notes.txt")
        ]))

        XCTAssertEqual(capture.kind, .file)
        XCTAssertEqual(capture.title, "report.pdf, notes.txt")
        XCTAssertEqual(capture.filePaths, ["/Users/me/Desktop/report.pdf", "/Users/me/notes.txt"])
        XCTAssertEqual(capture.representations.map(\.itemIndex), [0, 1])
    }

    func testFilesWinOverTheirTextName() throws {
        let item = ClipPasteboardItem(
            types: ["public.file-url", "public.utf8-plain-text"],
            data: [
                "public.file-url": Data(URL(fileURLWithPath: "/tmp/a.png").absoluteString.utf8),
                "public.utf8-plain-text": Data("a.png".utf8)
            ]
        )
        XCTAssertEqual(ClipCapturePolicy.capture([item])?.kind, .file)
    }

    func testImageWithoutTextIsAnImageClip() throws {
        let item = ClipPasteboardItem(types: ["public.png"], data: ["public.png": Data([1, 2, 3])])
        let capture = try XCTUnwrap(ClipCapturePolicy.capture([item]))

        XCTAssertEqual(capture.kind, .image)
        XCTAssertEqual(capture.title, "Image")
    }

    func testTextWinsOverAPreviewImage() {
        let item = ClipPasteboardItem(
            types: ["public.utf8-plain-text", "public.png"],
            data: ["public.utf8-plain-text": Data("cell".utf8), "public.png": Data([1])]
        )
        XCTAssertEqual(ClipCapturePolicy.capture([item])?.kind, .text)
    }

    func testUnknownPrivateTypesAloneAreSkipped() {
        let item = ClipPasteboardItem(types: ["com.example.private"], data: ["com.example.private": Data([1])])
        XCTAssertNil(ClipCapturePolicy.capture([item]))
    }

    func testOversizedCopiesAreSkipped() {
        let big = Data(count: ClipCapturePolicy.maximumBytes + 1)
        let item = ClipPasteboardItem(
            types: ["public.utf8-plain-text", "public.tiff"],
            data: ["public.utf8-plain-text": Data("x".utf8), "public.tiff": big]
        )
        XCTAssertNil(ClipCapturePolicy.capture([item]))
    }

    func testSameTextFromDifferentAppsSharesAHash() throws {
        let plain = try XCTUnwrap(ClipCapturePolicy.capture([text("same")]))
        let rich = try XCTUnwrap(ClipCapturePolicy.capture([ClipPasteboardItem(
            types: ["public.html", "public.utf8-plain-text"],
            data: ["public.html": Data("<b>same</b>".utf8), "public.utf8-plain-text": Data("same".utf8)]
        )]))
        let other = try XCTUnwrap(ClipCapturePolicy.capture([text("different")]))

        XCTAssertEqual(plain.contentHash, rich.contentHash)
        XCTAssertNotEqual(plain.contentHash, other.contentHash)
    }

    func testLongTextTitleIsCapped() throws {
        let capture = try XCTUnwrap(ClipCapturePolicy.capture([text(String(repeating: "a", count: 5000))]))
        XCTAssertEqual(capture.title.count, 300)
    }

    private func text(_ string: String) -> ClipPasteboardItem {
        ClipPasteboardItem(types: ["public.utf8-plain-text"], data: ["public.utf8-plain-text": Data(string.utf8)])
    }

    private func file(_ path: String) -> ClipPasteboardItem {
        ClipPasteboardItem(
            types: ["public.file-url"],
            data: ["public.file-url": Data(URL(fileURLWithPath: path).absoluteString.utf8)]
        )
    }
}
